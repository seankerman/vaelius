-- Owner self-service controls (agenthub.owner_controls): find, delete, re-share
-- and grant one's own content without an operator, plus project moderation.
-- Additive: applied migrations stay immutable, and nothing becomes more visible.
--
-- * enterprise_organizations.owner_sharing: 'allowed' lets owners raise the stored
--   level of their own sources and grant them to named people or projects;
--   'lower_only' (an operator restriction) keeps lowering, deleting and revoking
--   but refuses raises and new owner grants, and switches off owner-issued grants
--   at query time. Grants issued with the operator `policy` action are unaffected.
-- * enterprise_documents.level_capped: derived (non-passage) documents registered
--   after this migration are capped by the sharing level of every source they
--   depend on, like passages. Existing documents keep the connection-visibility
--   rule (0) until an owner changes the sharing of a source they depend on.
-- * enterprise_documents.raw_granted: prefilter for passages whose source is
--   covered by an active passage grant. Only a prefilter; the grant check decides.
-- * raw_source_grants: generalized owner grants. A grant covers a source, a
--   capture session or a connection, and carries the tiers it grants: redacted
--   passages and/or retained originals. Existing grants were originals-only and
--   stay so (passages=0, originals=1, issued_with='policy').
-- * enterprise_sharing_changes: who changed which source's stored level, from
--   what, to what, what was asked for and which ceiling capped it.
-- * enterprise_sources.moderated_*: a project maintainer's withdrawal (hide).

ALTER TABLE enterprise_organizations ADD COLUMN IF NOT EXISTS owner_sharing TEXT NOT NULL DEFAULT 'allowed'
    CONSTRAINT enterprise_organizations_owner_sharing CHECK (owner_sharing IN ('allowed','lower_only'));

ALTER TABLE enterprise_documents ADD COLUMN IF NOT EXISTS level_capped SMALLINT NOT NULL DEFAULT 0;
ALTER TABLE enterprise_documents ALTER COLUMN level_capped SET DEFAULT 1;
ALTER TABLE enterprise_documents ADD COLUMN IF NOT EXISTS raw_granted SMALLINT NOT NULL DEFAULT 0;

DO $grants$
DECLARE item RECORD;
BEGIN
    FOR item IN SELECT c.conname FROM pg_constraint c
        JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=ANY(c.conkey)
        WHERE c.contype='c' AND c.connamespace=current_schema()::regnamespace
        AND c.conrelid='raw_source_grants'::regclass AND a.attname='scope_kind'
    LOOP
        EXECUTE format('ALTER TABLE raw_source_grants DROP CONSTRAINT %I',item.conname);
    END LOOP;
END $grants$;
ALTER TABLE raw_source_grants ADD CONSTRAINT raw_source_grants_scope_kind
    CHECK (scope_kind IN ('source','session','connection'));
ALTER TABLE raw_source_grants ADD COLUMN IF NOT EXISTS passages SMALLINT NOT NULL DEFAULT 0
    CONSTRAINT raw_source_grants_passages CHECK (passages IN (0,1));
ALTER TABLE raw_source_grants ADD COLUMN IF NOT EXISTS originals SMALLINT NOT NULL DEFAULT 1
    CONSTRAINT raw_source_grants_originals CHECK (originals IN (0,1));
ALTER TABLE raw_source_grants ADD COLUMN IF NOT EXISTS issued_with TEXT NOT NULL DEFAULT 'policy'
    CONSTRAINT raw_source_grants_issued_with CHECK (issued_with IN ('policy','share'));
ALTER TABLE raw_source_grants ADD COLUMN IF NOT EXISTS revoked_by TEXT;
